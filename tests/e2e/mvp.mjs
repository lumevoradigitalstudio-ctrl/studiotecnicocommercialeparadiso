// Percorso MVP su web export: onboarding → chat → pasto → riapertura. Uso: node tests/e2e/mvp.mjs <baseUrl>
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const base = process.argv[2] ?? "http://127.0.0.1:8099";
const assert = (c, m) => { if (!c) { console.error("FAIL:", m); process.exitCode = 1; throw new Error(m); } console.log("ok  -", m); };
const browser = await chromium.launch();
const ctx = await browser.newContext(); const page = await ctx.newPage();
const errors = []; page.on("pageerror", e => errors.push(String(e)));
await page.goto(base);
await page.getByText("RITMO AI").first().waitFor();
assert(await page.getByText("Mangia bene, anche quando la vita cambia programma.").isVisible(), "benvenuto mostrato");
await page.getByRole("button", { name: /Inizia/ }).click();
const cont = page.getByRole("button", { name: "Continua" });
assert(await cont.isDisabled(), "Continua disabilitato senza obiettivo e consenso");
await page.getByText("Organizzare i pasti").click();
await page.getByRole("checkbox", { name: "Vegetariano" }).click();
await page.getByLabel("Alimenti da escludere (separati da virgola)").fill("coriandolo");
await page.getByLabel("Consenso al trattamento delle preferenze alimentari").click();
assert(await cont.isEnabled(), "Continua abilitato dopo obiettivo+consenso");
await cont.click();
await page.getByText("Non sai cosa mangiare adesso?").waitFor();
assert(true, "Home aperta");
await page.getByRole("tab", { name: /La mia cucina/ }).click();
for (const i of ["Uova", "Patate", "Pomodori"]) { await page.getByLabel("Aggiungi ingrediente").fill(i); await page.getByRole("button", { name: "Aggiungi", exact: true }).click(); }
await page.getByText("Ricette con la tua dispensa").waitFor();
await page.getByRole("button", { name: "Vedi Frittata di patate" }).click();
await page.getByText("2 porzioni").waitFor();
await page.getByRole("button", { name: "Più porzioni" }).click();
await page.getByText("3 porzioni").waitFor();
await page.getByText("• patate: 450 g").waitFor();
assert(true, "ricetta scalata a 3 porzioni (patate 450 g)");
await page.getByText("Hai già tutto.").waitFor();
assert(true, "lista della spesa: nulla da comprare quando la dispensa copre la ricetta");
await page.getByRole("button", { name: "Vedi Pasta al pomodoro fresco" }).click();
await page.getByText("• pasta: 160 g").first().waitFor();
assert((await page.getByText("• pasta: 160 g").count()) === 2, "pasta compare tra gli ingredienti e in «Da comprare»");
await page.getByRole("tab", { name: /RITMO AI/ }).click();
await page.getByLabel("Scrivi a RITMO").fill("Ho uova, patate e pomodori");
await page.getByRole("button", { name: "Invia" }).click();
await page.getByText(/\[DEMO\].*frittata/i).waitFor({ timeout: 10000 });
assert(await page.getByText(/\[DEMO\]/).isVisible(), "risposta marcata DEMO e basata sulla dispensa");
await page.getByLabel("Scrivi a RITMO").fill("Sono incinta, che dieta faccio?");
await page.getByRole("button", { name: "Invia" }).click();
await page.getByText(/ginecologo/).waitFor({ timeout: 10000 });
assert(true, "guardrail gravidanza attivo");
await page.getByRole("tab", { name: /I miei pasti/ }).click();
await page.getByLabel("Cosa hai mangiato?").fill("Frittata di patate");
await page.getByRole("button", { name: "Salva pasto" }).click();
await page.getByText(/pranzo — Frittata di patate/).waitFor();
assert(true, "pasto salvato");
await page.getByRole("tab", { name: /Il mio percorso/ }).click();
await page.getByText("Hai registrato almeno un pasto in 1 giorni su 7.").waitFor();
assert(true, "percorso: 1 giorno su 7, tono neutro");
await page.reload();
await page.getByRole("tab", { name: /Home/ }).waitFor({ timeout: 10000 });
assert(true, "dopo riapertura: onboarding saltato (persistenza)");
await page.getByRole("tab", { name: /I miei pasti/ }).click();
await page.getByText(/pranzo — Frittata di patate/).waitFor({ timeout: 5000 });
assert(true, "pasto persistito dopo riapertura");
await page.getByRole("tab", { name: /La mia cucina/ }).click();
await page.getByText("Patate", { exact: true }).waitFor({ timeout: 5000 });
assert(true, "dispensa persistita");
assert(errors.length === 0, "nessun errore JS di pagina " + errors.join("|"));
await browser.close();
